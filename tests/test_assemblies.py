"""Assembly choice and biological-assembly expansion (symmetry-generated dimer counting)."""

from __future__ import annotations

from collections import Counter

import pytest

from psma_pipeline.assemblies import assembly_note, choose_assembly, oligomer_label


def asm(aid, details, count=2):
    return {"rcsb_id": f"1ABC-{aid}", "pdbx_struct_assembly": {"id": str(aid), "details": details,
                                                               "oligomeric_count": count}}


def test_author_assembly_preferred_over_software():
    a, why = choose_assembly([asm(1, "software_defined_assembly", 1), asm(2, "author_defined_assembly")])
    assert a["pdbx_struct_assembly"]["id"] == "2" and why.startswith("author-defined")


def test_author_and_software_counts_as_author():
    a, why = choose_assembly([asm(1, "author_and_software_defined_assembly")])
    assert "author" in why


def test_software_only_takes_lowest_numeric_id():
    a, why = choose_assembly([asm(10, "software_defined_assembly"), asm(2, "software_defined_assembly")])
    assert a["pdbx_struct_assembly"]["id"] == "2"
    assert why.startswith("software-defined only")


def test_fallback_to_first_and_empty():
    a, why = choose_assembly([asm(3, ""), asm(1, "")])
    assert a["pdbx_struct_assembly"]["id"] == "1" and why.startswith("fallback")
    assert choose_assembly([]) == (None, "no assembly defined")


def test_oligomer_labels_and_notes():
    assert oligomer_label(1) == "monomer" and oligomer_label(2) == "dimer" and oligomer_label(6) == "6-mer"
    assert oligomer_label(None) == "unknown"
    assert assembly_note(1, 2) == "assembly generated by symmetry (1 in ASU -> 2)"
    assert assembly_note(2, 2) == "assembly = asymmetric-unit content"
    assert assembly_note(2, None) == "assembly could not be evaluated"


def test_offline_survey_assembly_columns(offline_survey):
    s = offline_survey.tables["Summary"].set_index("PDB ID")
    assert s.loc["3CCC", "Assembly choice reason"].startswith("software-defined only")
    assert s.loc["1AAA", "Monomer / dimer"] == "dimer"
    # heteromeric cryo-EM entry: no coordinates -> copies cannot be inferred from chain count
    assert s.loc["4DDD", "Monomer / dimer"] == "unknown"


